#!/usr/bin/env python3
"""Turns abi_facts.txt (devkitA64's C ABI, from abi_dump.sh) into compile-time
assertions on the libc crate (third_party/libc) for the Switch target."""
import pathlib, sys
here = pathlib.Path(__file__).parent
skip = set(sys.argv[1:])
lines = ['#![no_std]', '#![allow(unused)]', '// Generated by gen_abi_check.py from abi_facts.txt. Do not edit.',
         'use core::mem::{align_of, offset_of, size_of};', '']
typemap = {'d_name': None, 'PATH_MAX_': None}
for raw in (here / 'abi_facts.txt').read_text().split('\n'):
    if not raw.strip():
        continue
    name, value = raw.split()
    value = int(value)
    if name in skip or name in typemap:
        continue
    if name.startswith('sizeof_') or name.startswith('alignof_'):
        kind, ty = name.split('_', 1)
        if ty == 'd_name':
            continue
        fn = 'size_of' if kind == 'sizeof' else 'align_of'
        lines.append(f'const _: () = assert!({fn}::<libc::{ty}>() == {value}, "{name}");')
    elif name.startswith('offsetof_'):
        rest = name[len('offsetof_'):]
        # offsetof_<type>_<field>; types may contain '_' (sockaddr_in6), fields start with a known prefix
        for split in range(len(rest)):
            if rest[split] == '_':
                ty, field = rest[:split], rest[split + 1:]
                if field.split('_')[0] in ('st', 'd', 'tv', 'sa', 'ss', 'sin', 'sin6', 'sun', 'ai', 'events', 'revents'):
                    break
        lines.append(f'const _: () = assert!(offset_of!(libc::{ty}, {field}) == {value}, "{name}");')
    else:
        lines.append(f'const _: () = assert!((libc::{name} as i64 as u32) == ({value}i64 as u32), "{name}");')
(here / 'abi_check' / 'src' / 'lib.rs').write_text('\n'.join(lines) + '\n')
print(len(lines) - 5, 'assertions')
